# Pedir as notas
# int() - converte pra numero inteiro
# float() - converte pra numero com decimal

# Conversão 1
nota1 = input("Digite sua primeira nota:")
nota1 = float(nota1)

# Conversão 2
nota2 = float(input("Digite sua segunda nota:"))

#Fazer o cálculo da média
media = (nota1 + nota2) / 2  

#Mostra a média 
print("A média foi:", media)