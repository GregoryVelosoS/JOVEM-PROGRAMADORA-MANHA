# Listas = Arrays
lista_convidados = ["Calleri", "Taylor Swift", "João", "Atena"]

# Mostrando o array inteiro
print(lista_convidados)

#Mostrar um índice específico através do número
print(lista_convidados[0])

#Mostrar todos os elementos através de uma repetição
for item in range(4):
    print(lista_convidados[item])

